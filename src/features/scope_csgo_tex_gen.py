# Regenerates scope_csgo_tex.h from csgo legacy pak01 (top DXT5 mip of the 3 scope textures).
# SAME FILE in SimpleVisual and fpsoverlay. Run: python scope_csgo_tex_gen.py
# Prints PIL-decoded reference sums -> paste into tests/scopecsgo_test.cpp if art changes.
import struct, os, io
ROOT = r"C:\Program Files (x86)\Steam\steamapps\common\csgo legacy\csgo"
HERE = os.path.dirname(os.path.abspath(__file__))
WANT = {  # vpk path -> C name
    "materials/sprites/scope_arc": "kScCsArc",
    "materials/sprites/scope_line_blur": "kScCsBlur",
    "materials/overlays/scope_lens": "kScCsLens",
}

def cstr(f):
    b = bytearray()
    while (c := f.read(1)) not in (b"\0", b""):
        b += c
    return b.decode("latin1")

def vpk_files():
    d = os.path.join(ROOT, "pak01_dir.vpk")
    out = {}
    with open(d, "rb") as f:
        _, ver, treesz = struct.unpack("<III", f.read(12))
        hdr = 12 if ver == 1 else 28
        f.seek(hdr)
        while ext := cstr(f):
            while path := cstr(f):
                while name := cstr(f):
                    _, pre, arch, off, ln, _ = struct.unpack("<IHHIIH", f.read(18))
                    data = f.read(pre)
                    key = f"{path}/{name}"
                    if ext == "vtf" and key in WANT:
                        src = d if arch == 0x7FFF else os.path.join(ROOT, "pak01_%03d.vpk" % arch)
                        base = hdr + treesz if arch == 0x7FFF else 0
                        with open(src, "rb") as a:
                            a.seek(base + off); data += a.read(ln)
                        out[key] = data
    return out

def top_dxt5(vtf):
    w, h = struct.unpack("<HH", vtf[16:20])
    fmt = struct.unpack("<i", vtf[52:56])[0]
    assert fmt == 15, "expected IMAGE_FORMAT_DXT5"
    sz = max(1, (w + 3) // 4) * max(1, (h + 3) // 4) * 16
    return w, h, vtf[-sz:]   # mips smallest->largest, top mip is last

def ref_sums(w, h, data):
    try:
        from PIL import Image
    except ImportError:
        return None
    dds = struct.pack("<4sIIIIIII44xII4sIIIIIIIII4x", b"DDS ", 124, 0x81007, h, w, len(data), 0, 1,
                      32, 4, b"DXT5", 0, 0, 0, 0, 0, 0x1000, 0, 0, 0) + data
    px = Image.open(io.BytesIO(dds)).convert("RGBA").tobytes()
    return [sum(px[c::4]) for c in range(4)], list(px[(h // 2 * w + w // 2) * 4:][:4])

files = vpk_files()
lines = ["#pragma once",
         "// GENERATED by scope_csgo_tex_gen.py from csgo legacy pak01 -- do not edit.",
         "// Top DXT5 mip of sprites/scope_arc, sprites/scope_line_blur, overlays/scope_lens.",
         "// SAME FILE in SimpleVisual and fpsoverlay."]
for key, cname in WANT.items():
    w, h, data = top_dxt5(files[key])
    lines.append(f"static constexpr int {cname}W = {w}, {cname}H = {h};")
    lines.append(f"static const unsigned char {cname}Dxt5[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        lines.append("".join(f"0x{b:02x}," for b in data[i:i + 32]))
    lines.append("};")
    print(cname, w, h, "PIL rgba sums / center texel:", ref_sums(w, h, data))
open(os.path.join(HERE, "scope_csgo_tex.h"), "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote scope_csgo_tex.h")
