// Lock-free single-producer / single-consumer ring buffer.
template<typename T, size_t N>
class SpscQueue {
    static_assert(N > 0, "");
    T                  m_buf[N + 1];
    std::atomic<size_t> m_read{0};
    std::atomic<size_t> m_write{0};
public:
    bool push(const T& v) {
        size_t w    = m_write.load(std::memory_order_relaxed);
        size_t next = (w + 1) % (N + 1);
        if (next == m_read.load(std::memory_order_acquire)) return false;
        m_buf[w] = v;
        m_write.store(next, std::memory_order_release);
        return true;
    }
    bool pop(T& v) {
        size_t r = m_read.load(std::memory_order_relaxed);
        if (r == m_write.load(std::memory_order_acquire)) return false;
        v = m_buf[r];
        m_read.store((r + 1) % (N + 1), std::memory_order_release);
        return true;
    }
};

