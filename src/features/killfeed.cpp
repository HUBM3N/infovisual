// ------------------------------------------------------------
// D3D9 sprite-sheet textures
// Slots 0-2: default (d_images / v2 / v3)
// Slots 3-5: consistent icons (d / d2 / d3 from improvedkillicons)
// ------------------------------------------------------------
static IDirect3DTexture9* s_kfTex[6]     = {};
static int                s_kfSheetW[6]  = { 512, 512, 512, 1024, 512, 512 };
static int                s_kfSheetH[6]  = { 512, 1024, 1024, 1024, 512, 1024 };

// Cached D3D device (set in KillfeedInit, used for on-demand SVG rasterization)
static IDirect3DDevice9*  s_kfDev        = nullptr;

// ------------------------------------------------------------
// SVG icon cache -- for weapon reskins that share an event weapon field
// (e.g. AWPer Hand defindex 851 uses "sniperrifle" event but has its own SVG)
// ------------------------------------------------------------
struct KfSvgIcon { int defIdx; int heightPx; IDirect3DTexture9* tex; int texW; };
static constexpr int k_kfSvgCacheSz = 8;
static KfSvgIcon     s_svgIconCache[k_kfSvgCacheSz] = {};

// Defindexes that should use their own SVG icon in the killfeed instead of the
// sprite sheet icon determined by the weapon event field.
static bool KfIsDefIdxSvgOverride(int defIdx)
{
    static const int k_overrides[] = {
        851,   // AWPer Hand  -- event says "sniperrifle"; this has its own distinct SVG
    };
    for (int d : k_overrides) if (d == defIdx) return true;
    return false;
}

// Returns (and lazily creates) a D3D9 texture for the weapon SVG at heightPx tall.
// Returns null if defIdx has no SVG entry or rasterization fails.
static IDirect3DTexture9* KfGetOrCreateSvgTex(int defIdx, int heightPx, int* outW)
{
    if (outW) *outW = 0;
    if (!s_kfDev || defIdx <= 0 || heightPx <= 0) return nullptr;
    for (int i = 0; i < k_kfSvgCacheSz; ++i) {
        if (s_svgIconCache[i].defIdx == defIdx && s_svgIconCache[i].heightPx == heightPx) {
            if (outW) *outW = s_svgIconCache[i].texW;
            return s_svgIconCache[i].tex;
        }
    }
    // Not cached -- rasterize via weaponhud helper.
    int w = 0;
    IDirect3DTexture9* tex = WpnHud_RasterizeForKf(s_kfDev, defIdx, heightPx, &w);
    if (!tex) return nullptr;
    // Evict the first empty slot, or slot 0 if full (simple LRU not needed for 8 entries).
    int slot = 0;
    for (int i = 0; i < k_kfSvgCacheSz; ++i) if (!s_svgIconCache[i].tex) { slot = i; break; }
    if (s_svgIconCache[slot].tex) s_svgIconCache[slot].tex->Release();
    s_svgIconCache[slot] = { defIdx, heightPx, tex, w };
    if (outW) *outW = w;
    return tex;
}

// ------------------------------------------------------------
// Kill entry ring buffer
// ------------------------------------------------------------
struct KillEntry {
    char   attackerName[128];
    char   victimName[128];
    bool   localIsAttacker;
    int    attackerTeam;   // 2=RED, 3=BLU, 0=unknown
    int    victimTeam;
    double birthTime;
    float  slidePos;
    float  slideVel;
    float  alpha;
    bool   active;
    bool   slidingOut;
    int    slideOutDir;   // +1 = exit right, -1 = exit left
    float  renderY;       // animated Y position; -9999 = unset (snap on first frame)
    float  renderYVel;
    // Icon sprite rect (-1 sheet = no icon)
    int    iconSheet;
    int    iconX, iconY, iconW, iconH;
    bool   iconCropToSquare;
    // Item definition index of the kill weapon (0 = unknown).
    // Used to override sprite icons with per-reskin SVGs when the event weapon field is generic.
    int    weaponDefIdx;
    // True when icon was derived from the plain weapon name; false when a customkill
    // case (headshot, backstab, etc.) set the icon. SVG override only applies when true.
    bool   iconIsPlainWeapon;
};

static constexpr int k_kfBufSize = 8;
// Render-thread-only active entries, oldest first, never more than k_kfBufSize.
static std::deque<KillEntry> s_entries;
// Lock-free hand-off: game thread pushes, render thread drains each Tick.
static SpscQueue<KillEntry, 8> s_pushQueue;

// ------------------------------------------------------------
// Cached deathnotice cvar pointer + saved original value
// ------------------------------------------------------------
static ConVar* s_deathNoticeCvar      = nullptr;
static float   s_savedDeathNoticeTime = 5.f;

// Raw ConVar write helper -- must be a standalone function (no C++ object unwinding)
// so __try is legal.
static __declspec(noinline) void KfWriteCvar(ConVar* cv, float fval, int ival)
{
    if (!cv) return;
    __try {
        uintptr_t base   = reinterpret_cast<uintptr_t>(cv);
        uintptr_t parent = *reinterpret_cast<uintptr_t*>(base + 0x38);
        if (parent < 0x10000 || parent > 0x7FFFFFFFFFFFull) parent = base;
        *reinterpret_cast<float*>(parent + 0x54) = fval;
        *reinterpret_cast<int*>  (parent + 0x58) = ival;
    } __except(EXCEPTION_EXECUTE_HANDLER) {}
}

// Public restore entry point so render.cpp doesn't need its own __try block.
void KillfeedRestoreNoticeTime()
{
    KfWriteCvar(s_deathNoticeCvar, s_savedDeathNoticeTime,
                static_cast<int>(s_savedDeathNoticeTime));
}

// ------------------------------------------------------------
// KillfeedPushEntry -- called from game thread (h_FireEvent)
// ------------------------------------------------------------
void KillfeedPushEntry(const char* attackerName, const char* victimName,
                       const char* iconName, bool localIsAttacker,
                       int attackerTeam, int victimTeam, int weaponDefIdx,
                       bool iconIsPlainWeapon)
{
    if (!g_customKillfeedEnable || !g_selfKillfeedOnly) return;

    // Resolve icon from compile-time table -- no engine calls, thread-safe.
    const KfIconDef* icon = nullptr;
    if (iconName && iconName[0])
        icon = g_kfConsistentIcons ? KfFindIconConsistent(iconName) : KfFindIcon(iconName);

    // Build the full entry on the game thread's stack -- no shared state touched.
    // s_pushQueue hands it to the render thread lock-free and drops the push
    // silently if full (won't happen at normal framerates).
    KillEntry e{};
    strncpy_s(e.attackerName, sizeof(e.attackerName), attackerName ? attackerName : "?", _TRUNCATE);
    strncpy_s(e.victimName,   sizeof(e.victimName),   victimName   ? victimName   : "?", _TRUNCATE);
    e.localIsAttacker = localIsAttacker;
    e.attackerTeam   = attackerTeam;
    e.victimTeam     = victimTeam;
    e.birthTime      = -1.0;   // stamped when the render thread drains it (ImGui is render-thread only)
    float initSlide;
    if      (g_kfSlideDir == 1) initSlide = -400.f;
    else if (g_kfSlideDir == 2) initSlide =  400.f;
    else                        initSlide = (g_kfOrigin == 0) ? -400.f : 400.f;
    e.slidePos    = g_kfSlideIn ? initSlide : 0.f;
    e.slideOutDir = (initSlide < 0.f) ? -1 : 1;
    e.slidingOut  = false;
    e.slideVel    = 0.f;
    e.alpha       = g_kfFadeIn ? 0.f : 1.f;
    e.renderY     = -9999.f;
    e.renderYVel  = 0.f;

    if (icon)
    {
        e.iconSheet = icon->sheet;
        e.iconX = icon->x; e.iconY = icon->y;
        e.iconW = icon->w; e.iconH = icon->h;
        e.iconCropToSquare = (strcmp(iconName, "d_skull") == 0 ||
                              strcmp(iconName, "d_skull_tf") == 0);
    }
    else
    {
        const KfIconDef* skull = (iconName && iconName[0]) ? KfFindIcon("d_skull") : nullptr;
        if (skull) {
            e.iconSheet = skull->sheet;
            e.iconX = skull->x; e.iconY = skull->y;
            e.iconW = skull->w; e.iconH = skull->h;
            e.iconCropToSquare = true;
        } else {
            e.iconSheet = -1;
            e.iconX = e.iconY = e.iconW = e.iconH = 0;
            e.iconCropToSquare = false;
        }
    }

    e.weaponDefIdx      = weaponDefIdx;
    e.iconIsPlainWeapon = iconIsPlainWeapon;
    e.active = true;

    s_pushQueue.push(e);
}

// ------------------------------------------------------------
// KillfeedInit -- lazily from KillfeedTick while the feature is on. s_kfDev doubles as the
// "tried" latch, so a failing sheet decode is not retried every frame; KillfeedUnload (reset,
// eject) clears it and the next tick rebuilds the D3DPOOL_DEFAULT sheets.
// ------------------------------------------------------------
static void KillfeedInit(IDirect3DDevice9* dev)
{
    s_kfDev = dev;
    if (s_kfTex[0]) return;  // already initialised

    struct { const unsigned char* data; unsigned int len; } sheets[6] = {
        { g_kfSheet0,  g_kfSheet0Len  },
        { g_kfSheet1,  g_kfSheet1Len  },
        { g_kfSheet2,  g_kfSheet2Len  },
        { g_kfCSheet0, g_kfCSheet0Len },
        { g_kfCSheet1, g_kfCSheet1Len },
        { g_kfCSheet2, g_kfCSheet2Len },
    };

    for (int i = 0; i < 6; ++i)
    {
        IDirect3DTexture9* stage = nullptr;
        HRESULT hr = D3DXCreateTextureFromFileInMemoryEx(
            dev, sheets[i].data, sheets[i].len,
            D3DX_DEFAULT, D3DX_DEFAULT, 1, 0, D3DFMT_A8R8G8B8, D3DPOOL_SYSTEMMEM,
            D3DX_FILTER_LINEAR, D3DX_FILTER_LINEAR, 0, nullptr, nullptr, &stage);

        if (SUCCEEDED(hr) && stage)
        {
            D3DSURFACE_DESC desc = {};
            stage->GetLevelDesc(0, &desc);
            s_kfSheetW[i] = (int)desc.Width;
            s_kfSheetH[i] = (int)desc.Height;

            IDirect3DTexture9* t = nullptr;
            dev->CreateTexture(desc.Width, desc.Height, 1, 0,
                               D3DFMT_A8R8G8B8, D3DPOOL_DEFAULT, &t, nullptr);
            if (t)
            {
                dev->UpdateTexture(stage, t);
                s_kfTex[i] = t;
                DebugLog("KillfeedInit: sheet[%d] %ux%u tex=%p", i, desc.Width, desc.Height, t);
            }
            stage->Release();
        }
        else
        {
            DebugLog("KillfeedInit: sheet[%d] D3DX failed hr=0x%08X", i, (unsigned)hr);
        }
    }
}

// ------------------------------------------------------------
// KillfeedUnload -- called on Reset and eject
// ------------------------------------------------------------
void KillfeedUnload()
{
    s_entries.clear();  // drop all live entries before textures are released

    for (int i = 0; i < 6; ++i)
    {
        if (s_kfTex[i]) { s_kfTex[i]->Release(); s_kfTex[i] = nullptr; }
    }
    for (int i = 0; i < k_kfSvgCacheSz; ++i)
    {
        if (s_svgIconCache[i].tex) { s_svgIconCache[i].tex->Release(); }
        s_svgIconCache[i] = {};
    }
    s_kfDev = nullptr;
    KfWriteCvar(s_deathNoticeCvar, s_savedDeathNoticeTime,
                static_cast<int>(s_savedDeathNoticeTime));
    s_deathNoticeCvar = nullptr;
}

// ------------------------------------------------------------
// KillfeedTick -- called each ImGui frame
// ------------------------------------------------------------
void KillfeedTick()
{
    // The menu only offers the custom feed under "Only your kills", so both flags gate it.
    if (!g_customKillfeedEnable || !g_selfKillfeedOnly) return;
    if (!s_kfDev && g_d3dDev) KillfeedInit(g_d3dDev);

    // Save hud_deathnotice_time so KillfeedUnload can restore it: leaving it at 0
    // after ejecting breaks icon capture on re-injection.
    if (!s_deathNoticeCvar && g_cvar)
    {
        s_deathNoticeCvar = g_cvar->FindVarWalk("hud_deathnotice_time");
        if (s_deathNoticeCvar)
        {
            uintptr_t base   = reinterpret_cast<uintptr_t>(s_deathNoticeCvar);
            uintptr_t parent = *reinterpret_cast<uintptr_t*>(base + 0x38);
            if (parent < 0x10000 || parent > 0x7FFFFFFFFFFFull) parent = base;
            float cur = *reinterpret_cast<float*>(parent + 0x54);
            s_savedDeathNoticeTime = (cur > 0.001f) ? cur : 5.f;
        }
    }

    // Drain entries pushed by the game thread (lock-free, render thread only).
    // Evict oldest if we're already at the user's display limit before inserting.
    {
        KillEntry pending{};
        while (s_pushQueue.pop(pending)) {
            if (pending.birthTime < 0.0) pending.birthTime = AnimTime();   // game time: host_framerate / timescale
            int limit = std::min(g_kfMaxEntries, k_kfBufSize);
            while (!s_entries.empty() && (int)s_entries.size() >= limit)
                s_entries.pop_front();
            s_entries.push_back(pending);
        }
    }

    if (!IsInGame()) return;

    // Suppress built-in TF2 killfeed. 0.00001 lets TF2 process the entry
    // (calling GetPlayerName etc.) before it expires, avoiding stale caches.
    // Visually identical to 0 — far below any frame time.
    KfWriteCvar(s_deathNoticeCvar, 0.00001f, 0);

    const float  dt      = AnimDt();
    const double now     = AnimTime();
    const float  screenW = ImGui::GetIO().DisplaySize.x;
    const float  screenH = ImGui::GetIO().DisplaySize.y;

    ImFont* font = (g_kfFont && g_kfFont->IsLoaded()) ? g_kfFont : ImGui::GetIO().FontDefault;
    const float fontSize = font->FontSize;

    const float iconH   = g_kfUseIcons ? (32.f * g_kfIconScale) : 0.f;
    const float iconPad = g_kfUseIcons ? 6.f : 0.f;
    const float padX    = g_kfPadX;
    const float padY    = 5.f;
    const float rowH    = (g_kfMinHeight > 0.f ? g_kfMinHeight : std::max(iconH, fontSize)) + padY * 2.f;

    ImDrawList* dl = ImGui::GetBackgroundDrawList();

    // Collect active entries — circular_buffer is render-thread-only, no lock needed.
    int order[k_kfBufSize]; int orderCount = 0;
    for (int i = 0; i < (int)s_entries.size(); ++i)
        if (s_entries[i].active) order[orderCount++] = i;
    for (int a = 0; a < orderCount - 1; ++a)
        for (int b = a + 1; b < orderCount; ++b)
        {
            bool swap = g_kfGrowDown
                ? (s_entries[order[a]].birthTime > s_entries[order[b]].birthTime)
                : (s_entries[order[a]].birthTime < s_entries[order[b]].birthTime);
            if (swap) { int t = order[a]; order[a] = order[b]; order[b] = t; }
        }

    int displayCount = std::min(orderCount, g_kfMaxEntries);

    // Compute entry widths: padX | attackerName | iconPad | icon | iconPad | victimName | padX
    // Name-live cycles the local attacker's name by time since the entry was born.
    float       entryWidths[k_kfBufSize] = {};
    const char* aNames[k_kfBufSize]      = {};
    float       aWidths[k_kfBufSize]     = {};
    for (int d = 0; d < displayCount; ++d)
    {
        int i = order[d];
        const char* aName = s_entries[i].attackerName;
        if (g_kfNameLive && s_entries[i].localIsAttacker && g_enableNameCycle && g_nameCount > 0 && g_nameInterval > 0.f) {
            int ci = (int)((now - s_entries[i].birthTime) / (double)g_nameInterval) % g_nameCount;
            aName = g_nameList[ci].text;
        }
        float aW = font->CalcTextSizeA(fontSize, FLT_MAX, 0.f, aName).x;
        aNames[d]  = aName;
        aWidths[d] = aW;
        float vW = font->CalcTextSizeA(fontSize, FLT_MAX, 0.f, s_entries[i].victimName).x;
        float iW = 0.f;
        if (g_kfUseIcons) {
            int defIdx = s_entries[i].weaponDefIdx;
            if (defIdx > 0 && s_entries[i].iconIsPlainWeapon && KfIsDefIdxSvgOverride(defIdx)) {
                // SVG icon: rasterize now (caches result) so width is known this frame.
                int svgW = 0;
                KfGetOrCreateSvgTex(defIdx, (int)iconH, &svgW);
                iW = (svgW > 0) ? (float)svgW : iconH;
            } else {
                int sh = s_entries[i].iconH, sw = s_entries[i].iconW;
                float nat = (sh > 0 && s_entries[i].iconSheet >= 0) ? (iconH * (float)sw / (float)sh) : iconH;
                iW = (s_entries[i].iconCropToSquare) ? std::min(iconH + 10.f, nat) : nat;
            }
        }
        entryWidths[d] = padX + aW + iconPad + iW + iconPad + vW + padX;
    }

    auto getBaseX = [&](float w) -> float {
        if (g_kfOrigin == 0) return g_kfOffsetX;
        if (g_kfOrigin == 1) return screenW - g_kfOffsetX - w;
        return screenW * 0.5f + g_kfOffsetX - w * 0.5f;
    };

    // Precompute target Y for each display slot (used for smooth-shift animation).
    float targetY[k_kfBufSize] = {};
    {
        float ty = g_kfOffsetY;
        for (int d = 0; d < displayCount; ++d)
        {
            targetY[d] = ty;
            ty += rowH + g_kfEntryPadY;
        }
    }

    for (int d = 0; d < displayCount; ++d)
    {
        int i = order[d];

        // Animate
        {
            KillEntry& e = s_entries[i];
            if (!e.active) continue;

            double age      = now - e.birthTime;
            double lifetime = (double)g_deathNoticeTime;

            if (age >= lifetime)
            {
                bool any = false;
                if (g_kfFadeOut) {
                    e.alpha = std::max(0.f, e.alpha - dt * g_kfFadeOutSpeed);
                    if (e.alpha > 0.f) any = true;
                }
                if (g_kfSlideOut) {
                    e.slidingOut = true;
                    float outTarget;
                    if      (g_kfSlideOutDir == 1) outTarget = -400.f;
                    else if (g_kfSlideOutDir == 2) outTarget =  400.f;
                    else                           outTarget = (float)e.slideOutDir * 400.f;
                    SpringToward(e.slidePos, e.slideVel, outTarget, dt, g_kfSlideOutSpeed * 2.f);
                    if (std::abs(e.slidePos) < 380.f) any = true;
                }
                if (!any) { e.active = false; continue; }
            }
            else if (g_kfFadeIn)
                e.alpha = std::min(1.f, e.alpha + dt * g_kfFadeSpeed);
            else
                e.alpha = 1.f;

            if (!e.slidingOut) {
                if (g_kfSlideIn)
                    SpringToward(e.slidePos, e.slideVel, 0.f, dt, g_kfSlideSpeed * 2.f);
                else
                    e.slidePos = 0.f;
            }

            if (g_kfSmoothShift) {
                if (e.renderY < -9000.f) e.renderY = targetY[d]; // snap on first frame
                SpringToward(e.renderY, e.renderYVel, targetY[d], dt, g_kfSmoothShiftSpeed * 2.f);
            } else {
                e.renderY = targetY[d];
            }
        }

        const KillEntry& se = s_entries[i];
        const float  alpha             = se.alpha;
        const float  slidePos          = se.slidePos;
        const float  entryRenderY      = se.renderY;
        const double birthTime         = se.birthTime;
        const char*  attackerName      = aNames[d];
        const char*  victimName        = se.victimName;
        const int    attackerTeam      = se.attackerTeam;
        const int    victimTeam        = se.victimTeam;
        const int    iconSheet         = se.iconSheet;
        const int    sprX = se.iconX, sprY = se.iconY, sprW = se.iconW, sprH = se.iconH;
        const bool   cropToSquare      = se.iconCropToSquare;
        const int    weaponDefIdx      = se.weaponDefIdx;
        const bool   iconIsPlainWeapon = se.iconIsPlainWeapon;

        float w     = entryWidths[d];
        float baseX = getBaseX(w) + slidePos;
        float x0    = baseX;
        float y0    = (entryRenderY < -9000.f) ? targetY[d] : entryRenderY;
        float x1    = x0 + w;
        float y1    = y0 + rowH;

        // Shadow
        if (g_kfBoxShadow)
            DrawBoxShadow(dl, x0, y0, x1, y1,
                g_kfBoxShadowOffX, g_kfBoxShadowOffY, g_kfBoxShadowBlur,
                g_kfBoxShadowColor, alpha, g_kfBgRounding, 0);

        // Background
        ImDrawFlags kfCF = CornerFlagsToImDraw(g_kfBgCornerFlags);
        ImU32 bgCol = ImGui::ColorConvertFloat4ToU32(
            ImVec4(g_kfBgColor[0], g_kfBgColor[1], g_kfBgColor[2], g_kfBgColor[3] * alpha));
        dl->AddRectFilled(ImVec2(x0, y0), ImVec2(x1, y1), bgCol, g_kfBgRounding, kfCF);

        // Blob gradient
        if (g_kfBlobEnable)
            DrawBlobGradient(dl, x0, y0, x1 - x0, y1 - y0,
                g_kfBlobColor, g_kfBlobAlpha * alpha,
                g_kfBlobSize, g_kfBlobSpeed, (float)d * 1.3f, g_kfBgRounding);

        // Outline layers
        if (g_kfOutlineLayerCount > 0)
            DrawOutlineLayers(dl, x0, y0, x1, y1, g_kfOutlineLayers, g_kfOutlineLayerCount, 1.f, g_kfBgRounding, g_kfBgCornerFlags, alpha);

        // Precipitation
        if (g_kfPrecipEnable) {
            float pc[4] = { g_kfPrecipColor[0], g_kfPrecipColor[1],
                            g_kfPrecipColor[2], g_kfPrecipColor[3] * alpha };
            DrawPrecipitation(dl, x0, y0, x1 - x0, y1 - y0,
                g_kfPrecipMode, g_kfPrecipCount, g_kfPrecipSpeed,
                g_kfPrecipSize, g_kfPrecipWind, pc, dt, i + 3);
        }

        // Kill glow (stroked rings around new entries)
        if (g_kfKillGlowEnable) {
            double age2 = now - birthTime;
            float glowA = 0.f;
            if (age2 < (double)g_kfKillGlowDuration) {
                float t = (float)(age2 / (double)g_kfKillGlowDuration);
                glowA = (1.f - t) * alpha;
            }
            if (glowA > 0.01f) {
                const int   kN     = 10;
                const float maxPx  = std::max(1.f, g_kfKillGlowSpread);
                const float stepPx = maxPx / (float)kN;
                const int   R = (int)(g_kfKillGlowColor[0] * 255);
                const int   G = (int)(g_kfKillGlowColor[1] * 255);
                const int   B = (int)(g_kfKillGlowColor[2] * 255);
                const float cA = g_kfKillGlowColor[3];
                for (int ri = kN - 1; ri >= 0; --ri) {
                    float expand = (ri + 0.5f) * stepPx;
                    float t2     = (float)ri / (float)(kN - 1);
                    int   ai     = (int)((1.f - t2) * glowA * cA * 200.f);
                    if (ai <= 0) continue;
                    dl->AddRect(ImVec2(x0 - expand, y0 - expand),
                                ImVec2(x1 + expand, y1 + expand),
                                IM_COL32(R, G, B, ai),
                                g_kfBgRounding + expand, kfCF, stepPx + 1.f);
                }
            }
        }

        float textY = y0 + padY + (rowH - padY * 2.f - fontSize) * 0.5f;

        // ---- Text draw helper (shadow + outline + base) ----
        auto drawText = [&](float tx, float ty, ImU32 col, const char* str) {
            if (g_kfTextOutline) {
                float ot = g_kfTextOutlineThickness;
                ImU32 oc = ImGui::ColorConvertFloat4ToU32(ImVec4(
                    g_kfTextOutlineColor[0], g_kfTextOutlineColor[1],
                    g_kfTextOutlineColor[2], g_kfTextOutlineColor[3] * alpha));
                if (font != ImGui::GetFont()) {
                    dl->AddText(font, fontSize, ImVec2(tx-ot, ty),    oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx+ot, ty),    oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx,    ty-ot), oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx,    ty+ot), oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx-ot, ty-ot), oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx+ot, ty-ot), oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx-ot, ty+ot), oc, str);
                    dl->AddText(font, fontSize, ImVec2(tx+ot, ty+ot), oc, str);
                } else {
                    dl->AddText(ImVec2(tx-ot, ty),    oc, str);
                    dl->AddText(ImVec2(tx+ot, ty),    oc, str);
                    dl->AddText(ImVec2(tx,    ty-ot), oc, str);
                    dl->AddText(ImVec2(tx,    ty+ot), oc, str);
                    dl->AddText(ImVec2(tx-ot, ty-ot), oc, str);
                    dl->AddText(ImVec2(tx+ot, ty-ot), oc, str);
                    dl->AddText(ImVec2(tx-ot, ty+ot), oc, str);
                    dl->AddText(ImVec2(tx+ot, ty+ot), oc, str);
                }
            }
            if (g_kfTextDropShadow) {
                float ox = g_kfTextDropShadowOffX, oy = g_kfTextDropShadowOffY;
                if (g_kfTextDropShadowBlur) {
                    const float bO[][2] = {
                        {ox-1,oy-1},{ox,oy-1},{ox+1,oy-1},
                        {ox-1,oy  },{ox,oy  },{ox+1,oy  },
                        {ox-1,oy+1},{ox,oy+1},{ox+1,oy+1}
                    };
                    ImU32 sc = ImGui::ColorConvertFloat4ToU32(ImVec4(
                        g_kfTextDropShadowColor[0], g_kfTextDropShadowColor[1],
                        g_kfTextDropShadowColor[2], g_kfTextDropShadowColor[3] * alpha * 0.35f));
                    if (font != ImGui::GetFont())
                        for (auto& b : bO) dl->AddText(font, fontSize, ImVec2(tx+b[0], ty+b[1]), sc, str);
                    else
                        for (auto& b : bO) dl->AddText(ImVec2(tx+b[0], ty+b[1]), sc, str);
                } else {
                    ImU32 sc = ImGui::ColorConvertFloat4ToU32(ImVec4(
                        g_kfTextDropShadowColor[0], g_kfTextDropShadowColor[1],
                        g_kfTextDropShadowColor[2], g_kfTextDropShadowColor[3] * alpha));
                    if (font != ImGui::GetFont())
                        dl->AddText(font, fontSize, ImVec2(tx+ox, ty+oy), sc, str);
                    else
                        dl->AddText(ImVec2(tx+ox, ty+oy), sc, str);
                }
            }
            if (font != ImGui::GetFont())
                dl->AddText(font, fontSize, ImVec2(tx, ty), col, str);
            else
                dl->AddText(ImVec2(tx, ty), col, str);
        };

        // ---- Attacker name ----
        auto attackerColF = [&]() -> ImVec4 {
            if (attackerTeam == 2)
                return ImVec4(g_kfRedColor[0], g_kfRedColor[1], g_kfRedColor[2], g_kfRedColor[3] * alpha);
            if (attackerTeam == 3)
                return ImVec4(g_kfBluColor[0], g_kfBluColor[1], g_kfBluColor[2], g_kfBluColor[3] * alpha);
            return ImVec4(g_kfTextColor[0], g_kfTextColor[1], g_kfTextColor[2], g_kfTextColor[3] * alpha);
        };
        ImU32 aCol = ImGui::ColorConvertFloat4ToU32(attackerColF());
        float curX = x0 + padX;
        drawText(curX, textY, aCol, attackerName);
        curX += aWidths[d];

        // ---- Icon (drawn directly via ImGui AddImage -- safe from render thread) ----
        curX += iconPad;
        if (g_kfUseIcons)
        {
            bool drewIcon = false;
            // SVG override: weapon is a reskin whose event field maps to a different weapon's sprite.
            // Only applies for plain weapon-name icons; customkill-derived icons (headshot etc.) pass through.
            if (weaponDefIdx > 0 && iconIsPlainWeapon && KfIsDefIdxSvgOverride(weaponDefIdx))
            {
                int svgTexW = 0;
                IDirect3DTexture9* svgTex = KfGetOrCreateSvgTex(weaponDefIdx, (int)iconH, &svgTexW);
                if (svgTex && svgTexW > 0)
                {
                    float iw  = (float)svgTexW;
                    float iy0 = y0 + padY + (rowH - padY * 2.f - iconH) * 0.5f;
                    float iy1 = iy0 + iconH;
                    float ix0 = curX;
                    float ix1 = ix0 + iw;
                    ImU32 iconCol = ImGui::ColorConvertFloat4ToU32(
                        ImVec4(g_kfIconColor[0], g_kfIconColor[1], g_kfIconColor[2], g_kfIconColor[3] * alpha));
                    dl->AddImage((ImTextureID)(uintptr_t)svgTex,
                        ImVec2(ix0, iy0), ImVec2(ix1, iy1), { 0, 0 }, { 1, 1 }, iconCol);
                    curX = ix1;
                    drewIcon = true;
                }
            }
            if (!drewIcon)
            {
                if (iconSheet >= 0 && s_kfTex[iconSheet] && sprH > 0)
                {
                    float naturalW = iconH * ((float)sprW / (float)sprH);
                    float iw  = cropToSquare ? std::min(iconH + 10.f, naturalW) : naturalW;
                    float iy0 = y0 + padY + (rowH - padY * 2.f - iconH) * 0.5f;
                    float iy1 = iy0 + iconH;
                    float ix0 = curX;
                    float ix1 = ix0 + iw;

                    float sw = (float)s_kfSheetW[iconSheet];
                    float sh = (float)s_kfSheetH[iconSheet];
                    ImVec2 uv0, uv1;
                    if (cropToSquare && iw < naturalW) {
                        float visSprW  = iw * (float)sprH / iconH;
                        float cropLeft = ((float)sprW - visSprW) * 0.5f;
                        uv0 = { (sprX + cropLeft) / sw,            sprY / sh };
                        uv1 = { (sprX + cropLeft + visSprW) / sw,  (sprY + sprH) / sh };
                    } else {
                        uv0 = { sprX / sw,           sprY / sh };
                        uv1 = { (sprX + sprW) / sw,  (sprY + sprH) / sh };
                    }

                    ImU32 iconCol = ImGui::ColorConvertFloat4ToU32(
                        ImVec4(g_kfIconColor[0], g_kfIconColor[1], g_kfIconColor[2], g_kfIconColor[3] * alpha));

                    dl->AddImage((ImTextureID)(uintptr_t)s_kfTex[iconSheet],
                        ImVec2(ix0, iy0), ImVec2(ix1, iy1), uv0, uv1, iconCol);

                    curX = ix1;
                }
                else
                {
                    curX += iconH;  // placeholder width when no icon
                }
            }
        }
        curX += iconPad;

        // ---- Victim name ----
        auto victimColF = [&]() -> ImVec4 {
            if (victimTeam == 2)
                return ImVec4(g_kfRedColor[0], g_kfRedColor[1], g_kfRedColor[2], g_kfRedColor[3] * alpha);
            if (victimTeam == 3)
                return ImVec4(g_kfBluColor[0], g_kfBluColor[1], g_kfBluColor[2], g_kfBluColor[3] * alpha);
            return ImVec4(g_kfTextColor[0], g_kfTextColor[1], g_kfTextColor[2], g_kfTextColor[3] * alpha);
        };
        ImU32 vCol = ImGui::ColorConvertFloat4ToU32(victimColF());
        drawText(curX, textY, vCol, victimName);
    }

    // Remove expired entries from the circular_buffer (render thread only, no lock needed).
    auto it = s_entries.begin();
    while (it != s_entries.end()) {
        if (!it->active) it = s_entries.erase(it);
        else             ++it;
    }
}
